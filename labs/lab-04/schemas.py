
from pydantic import BaseModel, Field
from typing import List, Literal



class Flashcard(BaseModel):
    """Each flashcard object format"""
    application: str = Field(..., description="1-2 sentence real-world workplace task where this concept is needed")
    challenge: str = Field(..., description="A specific problem to solve in the scenario. Expand all acronyms")
    answer: str = Field(..., description="Correct solution with brief explanation")
    evidence: str = Field(..., description="Direct quote from source notes supporting this card")
    misconception: str = Field(..., description="Quote of what a junior developer/student might incorrectly believe")
    correction: str = Field(..., description="Why it's wrong, citing the notes")
    
    

class FlashcardResponse(BaseModel):
    """Flashcards list object returned by the API. It contains a list of flashcards."""
    flashcards: List[Flashcard] = Field(..., description="List of flashcard objects generated by the API")
    message : str = Field(..., description="Explanation of whether the flashcards were generated successfully or not enough information was provided in the notes to generate the flashcards")

